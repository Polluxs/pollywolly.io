	</p>
	<h1 class="display mt-4 text-4xl text-balance text-ink sm:text-5xl">
		Hoe bereik je ondernemers <span class="marker">zonder iets te verkopen</span>?
	</h1>

	<p class="mt-10">
		Jarenlang werkte ik als freelancer, via tussenpersonen en grote projecten met duizend regels. Nu
		wilde ik ondernemers rechtstreeks helpen. Daarvoor moest ik ze eerst bereiken.
	</p>
	<p class="mt-4">
		Maar hoe? Koud bellen zonder cases of referenties, dan is de eerste vraag: wie bent u, en waarom
		zou ik naar u luisteren? Er zijn al genoeg softwarebedrijven. En wie zo werkt, is altijd bezig
		met de volgende klant zoeken. Advertenties kosten geld, en een ondernemer scrolt over nog een
		softwarebedrijf heen.
	</p>
	<p class="mt-4">
		Dus draaide ik de vraag om. Ik had geen beter verkooppraatje nodig, maar een manier waarop
		ondernemers zelf bij mij uitkomen. Welk probleem heeft elke ondernemer, dat ik gratis kan
		oplossen? In marketing heet dat een lead magnet: iets waardevols weggeven, zodat de juiste
		mensen bij u uitkomen.
	</p>

	<h2 class="display mt-14 text-2xl text-ink">Elke ondernemer zoekt weleens een bedrijf op</h2>
	<p class="mt-4">
		Een nieuwe klant, een leverancier, een concurrent. Maar die informatie stond verspreid over drie
		overheidssites: de KBO voor de gegevens, de Nationale Bank voor de jaarrekeningen, het
		Staatsblad voor wie er eigenaar is. Of ze zat bij een site die het antwoord achter een
		betaalmuur zette.
	</p>
	<p class="mt-4">
		Dus bouwde ik één pagina per bedrijf, voor elk van de meer dan 2 miljoen Belgische
		ondernemingen. Gratis en zonder slotjes, want een lead magnet die de helft verbergt, trekt
		niemand aan. Dat werd Databakkes.
	</p>

	<h2 class="display mt-14 text-2xl text-ink">Eerst één ding dat werkt</h2>
	<p class="mt-4">
		De eerste versie ging in december 2025 online en kon één ding: een bedrijf opzoeken in de KBO.
		Meer niet. Maar het werkte, en zoekmachines begonnen de pagina's te vinden.
	</p>

	<h2 class="display mt-14 text-2xl text-ink">Maar niet alleen ondernemers vonden het</h2>
	<p class="mt-4">
		In april legde de AI-crawler van Meta de site plat. Hij wilde elke pagina lezen, in drie talen,
		dag en nacht, en de server viel elke vier uur om.
	</p>
	<p class="mt-4">
		De boosdoener was een bekende vertaalmodule, die ik er zelf in had gestoken. Voor elke pagina
		rekende hij opnieuw uit hoe elke link in elke taal moest heten, en dat op een omslachtige
		manier: bijna alle rekentijd van elke pagina ging eraan op. Eerst een snel lapmiddel, zodat de
		site overeind bleef. Daarna haalde ik de module eruit en schreef ik de vertaling van links zelf,
		zodat het niet meer kan gebeuren.
	</p>
	<p class="mt-4">
		Veel werk voor een gratis product? Dezelfde gegevens vindt u ondertussen ook elders, en er komen
		er meer bij. Het verschil zit in hoe vlot het werkt. En wie op een draaiend wieltje zit te
		wachten, gaat mij geen software toevertrouwen. Dus maakte ik het niet alleen weer stabiel, ik
		trok het door: de server bouwt een pagina nu in 15 tot 20 milliseconden.
	</p>

	<h2 class="display mt-14 text-2xl text-ink">Dus kon het groeien</h2>
	<p class="mt-4">
		Nu het standhield, kwam telkens de volgende vraag van een ondernemer erbij. Hoe staat het
		bedrijf ervoor? Dus kwamen in augustus de jaarrekeningen van de Nationale Bank erbij. Wie zit er
		aan het roer? Dus de bestuurders en aandeelhouders.
	</p>
	<p class="mt-4">
		Maar steeds meer ondernemers stellen hun vraag aan ChatGPT of Claude in plaats van aan Google.
		Dus kunnen AI-assistenten Databakkes sinds september rechtstreeks bevragen.
	</p>

	<h2 class="display mt-14 text-2xl text-ink">Vandaag draait het zonder mij</h2>
	<p class="mt-4">
		Meer dan 500.000 opvragingen per week, vooral van zoekmachines en AI. Elke nacht haalt
		Databakkes zelf de nieuwe gegevens binnen, en elke ochtend controleert het zichzelf. Zo moet het
		ondernemers bij mij brengen.
	</p>

